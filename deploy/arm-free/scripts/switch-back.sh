#!/usr/bin/env bash
# switch-back.sh - return to the PC as primary after a failover.
#
# PROCEDURE (what this script automates, in order):
#   1. Stop the standby Immich stack (docker compose down; the Postgres data dir
#      /srv/orbit/immich-standby-db is kept, but is discarded by the next promote restore).
#   2. Export assets uploaded to the standby during the outage: every file under
#      <UPLOAD_LOCATION>/upload newer than the promotion timestamp
#      ($ORBIT_STATE_DIR/promoted-at) is copied to /srv/orbit/standby-uploads-<date>.
#      Re-upload them on the PC afterwards through the Immich app or the Immich CLI
#      (`immich upload --recursive <dir>`), because the PC database does not know
#      about them. (Thumbnails/encoded video are regenerated by the PC.)
#   3. Set the replica folders back to Receive Only and "Revert Local Changes"
#      (POST /rest/db/revert?folder=ID) so the standby's library goes back to
#      mirroring the PC exactly. Anything the standby wrote locally is discarded
#      (that is why step 2 comes first!).
#   4. Resume the folders.
#
# Before running: make sure the PC is back, Immich is running there, and its Syncthing
# folder "immich-library" is Send Only and connected to arm-free.
#
# Usage: switch-back.sh [--yes] [--skip-export]
# Env:   SYNCTHING_URL, SYNCTHING_CONFIG, PROMOTE_FOLDERS, ORBIT_STATE_DIR
set -euo pipefail

# shellcheck source=lib.sh
source "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/lib.sh"

# Not applicable when Immich runs here permanently (arm-free primary mode).
if [ "$(env_file_get "${ARM_FREE_DIR}/.env" ORBIT_PRIMARY_MODE)" = "arm-free" ]; then
  die "ORBIT_PRIMARY_MODE=arm-free: this VM is the primary, there is nothing to promote or switch back. See docs/failover-restore.md, section 'Disaster recovery (arm-free primary)'."
fi

YES=0
SKIP_EXPORT=0
for a in "$@"; do
  case "$a" in
    --yes|-y) YES=1 ;;
    --skip-export) SKIP_EXPORT=1 ;;
    -h|--help) sed -n '2,25p' "${BASH_SOURCE[0]}"; exit 0 ;;
    *) die "unknown argument: $a" ;;
  esac
done

need docker curl jq sed find rsync
ST_URL="${SYNCTHING_URL:-http://127.0.0.1:8384}"
ST_CONFIG="${SYNCTHING_CONFIG:-${ORBIT_ROOT}/syncthing-config/config.xml}"
FOLDERS="${PROMOTE_FOLDERS:-immich-library immich-db-dumps}"
ENV_FILE="${ARM_FREE_DIR}/immich/.env"
STATE_FILE="${ORBIT_STATE_DIR}/promoted-at"
UPLOAD_LOCATION="$(env_file_get "$ENV_FILE" UPLOAD_LOCATION)"
UPLOAD_LOCATION="${UPLOAD_LOCATION:-${ORBIT_ROOT}/immich-library}"
dc() { docker compose -f "$IMMICH_COMPOSE" --project-directory "$(dirname "$IMMICH_COMPOSE")" "$@"; }

if [ "$YES" -ne 1 ]; then
  echo "This stops standby Immich and REVERTS local changes in: ${FOLDERS}"
  read -r -p "Continue? [y/N] " ans
  [ "$ans" = "y" ] || [ "$ans" = "Y" ] || die "aborted"
fi

[ -r "$ST_CONFIG" ] || die "cannot read ${ST_CONFIG}"
API_KEY="$(sed -n 's:.*<apikey>\(.*\)</apikey>.*:\1:p' "$ST_CONFIG" | head -n 1)"
[ -n "$API_KEY" ] || die "no apikey in ${ST_CONFIG}"
st() { curl -fsS -m 30 -H "X-API-Key: ${API_KEY}" -H 'Content-Type: application/json' "$@"; }

# 1. stop standby ------------------------------------------------------------------------
log "Step 1/4: stopping standby Immich"
dc down

# 2. export uploads ----------------------------------------------------------------------
if [ "$SKIP_EXPORT" -eq 0 ]; then
  log "Step 2/4: exporting assets uploaded during the outage"
  if [ -f "$STATE_FILE" ]; then
    SINCE="$(cat "$STATE_FILE")"
    OUT="${ORBIT_ROOT}/standby-uploads-$(date +%Y%m%d)"
    SRC="${UPLOAD_LOCATION}/upload"
    if [ -d "$SRC" ]; then
      mkdir -p "$OUT"
      # -newermt with the stored UTC timestamp; copy keeping relative paths.
      find "$SRC" -type f -newermt "$SINCE" -printf '%P\0' \
        | rsync -a --from0 --files-from=- "${SRC}/" "${OUT}/"
      COUNT="$(find "$OUT" -type f | wc -l)"
      log "  ${COUNT} file(s) copied to ${OUT}"
      echo "  -> re-upload them on the PC (Immich app or: immich upload --recursive '${OUT}')"
    else
      warn "${SRC} not found; nothing to export"
    fi
  else
    warn "no promotion timestamp (${STATE_FILE}); skipping export"
  fi
else
  log "Step 2/4: export skipped (--skip-export)"
fi

# 3. revert local changes ----------------------------------------------------------------
log "Step 3/4: reverting replica folders to Receive Only"
for f in $FOLDERS; do
  st -X PATCH -d '{"type":"receiveonly"}' "${ST_URL}/rest/config/folders/${f}" >/dev/null \
    || { warn "could not set ${f} to receiveonly"; continue; }
  st -X POST "${ST_URL}/rest/db/revert?folder=${f}" >/dev/null \
    && log "  revert requested for ${f}" || warn "revert failed for ${f}"
done

# 4. resume ------------------------------------------------------------------------------
log "Step 4/4: resuming folders"
for f in $FOLDERS; do
  st -X PATCH -d '{"paused":false}' "${ST_URL}/rest/config/folders/${f}" >/dev/null \
    && log "  resumed ${f}" || warn "could not resume ${f}"
done

rm -f "$STATE_FILE"
log "Done. arm-free is a replica again; watch the sync in the Orbit dashboard."
notify_discord "Orbit: arm-free switched back to replica; PC is primary again."
